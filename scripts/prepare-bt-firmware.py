#!/usr/bin/env python3
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
FW_DIR = ROOT / "firmware"
OUT_HPP = ROOT / "src" / "QcaBtPayload.hpp"

def emit_array(name: str, data: bytes) -> list[str]:
    lines = [f"static constexpr UInt8 {name}[] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i+16]) + ",")
    lines.append("};")
    return lines

def main() -> None:
    profiles = []
    for rp in sorted(FW_DIR.glob("rampatch_usb_*.bin")):
        m = re.fullmatch(r"rampatch_usb_([0-9a-fA-F]{8})\.bin", rp.name)
        if not m:
            continue
        rom_hex = m.group(1).lower()
        nvm = FW_DIR / f"nvm_usb_{rom_hex}.bin"
        if not nvm.exists():
            continue
        profiles.append((int(rom_hex, 16), rom_hex, rp.read_bytes(), nvm.read_bytes()))

    if not profiles:
        raise SystemExit("No matching rampatch_usb_<rom>.bin + nvm_usb_<rom>.bin pairs in firmware/")

    out = [
        "// Generated by scripts/prepare-bt-firmware.py. Do not edit.",
        "#pragma once",
        '#include "QcaBtPayloadProfile.hpp"',
        "namespace QcaBtPayload {",
    ]
    entries = []
    for rom_val, rom_hex, rp_bytes, nvm_bytes in profiles:
        out.extend(emit_array(f"kRampatch_{rom_hex}", rp_bytes))
        out.extend(emit_array(f"kNvm_{rom_hex}", nvm_bytes))
        entries.append(
            f"    {{0x{rom_val:08x}u, kRampatch_{rom_hex}, sizeof(kRampatch_{rom_hex}), "
            f"kNvm_{rom_hex}, sizeof(kNvm_{rom_hex})}},"
        )

    out += [
        "static constexpr FirmwareProfile kProfiles[] = {",
        *entries,
        "};",
        "const FirmwareProfile *selectProfile(UInt32 romVersion) {",
        "    for (const auto &p : kProfiles)",
        "        if (p.romVersion == romVersion) return &p;",
        "    return nullptr;",
        "}",
        "} // namespace QcaBtPayload",
        "",
    ]
    OUT_HPP.write_text("\n".join(out))
    print(f"Generated {OUT_HPP} with {len(profiles)} QCA ROM profile(s).")

if __name__ == "__main__":
    main()
